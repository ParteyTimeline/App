const SUPPORTED_LANGS = ['de', 'en'];
const LANG_STORAGE_KEY = 'partey_lang';

function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_STORAGE_KEY);
    if (SUPPORTED_LANGS.includes(saved)) return saved;
  } catch (e) { /* localStorage unavailable (private mode etc.) */ }
  const nav = (navigator.language || navigator.userLanguage || 'de').toLowerCase();
  return nav.startsWith('de') ? 'de' : 'en';
}

let LANG = detectLang();

function setLang(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) return;
  LANG = lang;
  document.documentElement.lang = lang;
  try { localStorage.setItem(LANG_STORAGE_KEY, lang); } catch (e) { /* ignore */ }
}
document.documentElement.lang = LANG;

function t(key, vars) {
  let s = (STRINGS[LANG] && STRINGS[LANG][key]) ?? STRINGS.de[key] ?? key;
  if (vars) for (const k of Object.keys(vars)) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}

// German only pluralizes a handful of the counts we render (Karte/Karten,
// Fehlversuch/Fehlversuche) — everything else reads fine in both languages
// with a single plural form, so this is only used where the singular
// actually differs.
function tCount(base, n, vars) {
  return t(`${base}.${n === 1 ? 'one' : 'other'}`, { n, ...vars });
}
